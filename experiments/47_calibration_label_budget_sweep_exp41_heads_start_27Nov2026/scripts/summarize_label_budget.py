#!/usr/bin/env python3
"""Summarize Experiment 47 rows into tables and figures. Usage: python summarize_label_budget.py RESULTS_DIR FIG_DIR"""
import json, sys
from pathlib import Path
import numpy as np
import matplotlib; matplotlib.use("Agg"); import matplotlib.pyplot as plt

res, figd = Path(sys.argv[1]), Path(sys.argv[2]); figd.mkdir(parents=True, exist_ok=True)
rows = json.loads((res / "label_budget_rows.json").read_text())
NS = [25, 50, 100, 200, 500, 1000, "all"]; TH = 0.0024
views = sorted({r["view"] for r in rows}, key=lambda v: [r["view"] for r in rows].index(v))
summ = []
for design in ("R1", "RA"):
    for v in views:
        rv = [r for r in rows if r["view"] == v and r["design"] == design]
        line = {"design": design, "view": v, "signal": rv[0]["signal"], "n_val": rv[0]["n_val"], "cells": {}}
        nstar = None
        for n in NS:
            c = [r for r in rv if r["n_requested"] == n]
            G = np.concatenate([r["G_draws"] for r in c]); M = np.concatenate([r["M_draws"] for r in c])
            gm = float(np.mean([r["G_mean"] for r in c])); mm = float(np.mean([r["M_mean"] for r in c]))
            line["cells"][str(n)] = {"n_used": c[0]["n_used"], "G_mean": gm, "G_sd_seed_draw": float(G.std(ddof=1)) if len(G) > 1 else 0.0,
                                     "G_p95_seed_draw": float(np.percentile(G, 95)), "M_mean": mm, "M_sd_seed_draw": float(M.std(ddof=1)) if len(M) > 1 else 0.0,
                                     "E_mean": float(np.mean([r["E_mean"] for r in c])),
                                     "seeds_G_ci_above_0": int(sum(r["G_ci"][0] > 0 for r in c)), "seeds_G_ci_below_0": int(sum(r["G_ci"][1] < 0 for r in c))}
            if nstar is None and gm <= TH:
                nstar = n
        line["n_star"] = nstar if nstar is not None else "not reached"
        summ.append(line)
(res / "label_budget_summary.json").write_text(json.dumps(summ, indent=1))
with open(res / "label_budget_tables.md", "w") as f:
    f.write("# Experiment 47 tables (generated by scripts/summarize_label_budget.py)\n\n")
    f.write("Test split, normalized ranked probability score (RPS divided by K - 1; 0-1; lower is better). G(n) = test normalized RPS of the Pearson-trained head passed through a calibration map fitted on n validation labels, minus test normalized RPS of the CE-trained head used raw; positive = the CE-trained raw head is better. M(n) = the same Pearson-trained calibrated head minus the CE-trained head with a map fitted on the same n labels. Cells: mean over 5 split seeds x 20 calibration draws, then (SD over the 100 seed-draw cells). R1 = n items with one rating each (n labels); RA = n items with all their ratings. n is capped at the validation size.\n\n")
    for design in ("R1", "RA"):
        f.write(f"## Design {design}: G(n) mean (SD)\n\n| view | signal | n_val | " + " | ".join(f"n={n}" for n in NS) + " | n\\* (G <= 0.0024) |\n|" + "---|" * (len(NS) + 4) + "\n")
        for line in [l for l in summ if l["design"] == design]:
            f.write(f"| {line['view']} | {'yes' if line['signal'] else 'no'} | {line['n_val']} | " + " | ".join(
                f"{line['cells'][str(n)]['G_mean']:+.4f} ({line['cells'][str(n)]['G_sd_seed_draw']:.4f})" for n in NS) + f" | {line['n_star']} |\n")
        f.write(f"\n## Design {design}: M(n) mean (SD)\n\n| view | " + " | ".join(f"n={n}" for n in NS) + " |\n|" + "---|" * (len(NS) + 1) + "\n")
        for line in [l for l in summ if l["design"] == design]:
            f.write(f"| {line['view']} | " + " | ".join(f"{line['cells'][str(n)]['M_mean']:+.4f} ({line['cells'][str(n)]['M_sd_seed_draw']:.4f})" for n in NS) + " |\n")
        f.write("\n")
fig, axes = plt.subplots(1, 2, figsize=(13, 5))
for ax, design in zip(axes, ("R1", "RA")):
    for line in [l for l in summ if l["design"] == design]:
        xs = [line["cells"][str(n)]["n_used"] for n in NS]; ys = [line["cells"][str(n)]["G_mean"] for n in NS]
        ax.plot(xs, ys, marker="o", lw=1, alpha=0.8, label=line["view"], ls="-" if line["signal"] else ":")
    ax.axhline(TH, color="k", ls="--", lw=1); ax.axhline(0, color="gray", lw=0.8); ax.set_xscale("log")
    ax.set_xlabel(f"calibration labels n (validation split; design {design})")
    ax.set_ylabel("G(n): test nRPS, calibrated Pearson-trained minus raw CE-trained")
    ax.grid(True, which="major"); ax.grid(True, which="minor", alpha=0.25)
    ax.set_title(f"Design {design}: dashed = 0.0024 (Exp 41 max matched gap)")
axes[1].legend(fontsize=6, ncol=2)
fig.tight_layout(); fig.savefig(figd / "label_budget_closure_gap.png", dpi=140)
fig, ax = plt.subplots(figsize=(7, 5))
for line in [l for l in summ if l["design"] == "R1"]:
    xs = [line["cells"][str(n)]["n_used"] for n in NS[:-1]]; ys = [line["cells"][str(n)]["G_sd_seed_draw"] for n in NS[:-1]]
    ax.plot(xs, ys, marker="o", lw=1, alpha=0.8)
xx = np.array([25, 1000]); ax.plot(xx, 0.02 * (xx / 25) ** -0.5, "k--", label="slope n^(-1/2)")
ax.set_xscale("log"); ax.set_yscale("log"); ax.grid(True, which="major"); ax.grid(True, which="minor", alpha=0.25)
ax.set_xlabel("calibration labels n (validation, one rating per item)"); ax.set_ylabel("SD of G(n) over 5 seeds x 20 draws (test nRPS)")
ax.legend(); fig.tight_layout(); fig.savefig(figd / "label_budget_sd.png", dpi=140)
print(open(res / "label_budget_tables.md").read())
