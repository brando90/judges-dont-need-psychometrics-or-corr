#!/usr/bin/env python3
"""Experiment 55: write results/key_numbers.md from the CSVs (no new computation beyond formatting). Usage: python summarize.py [RESULTS_DIR]"""
import csv
import json
import sys
from pathlib import Path

RES = Path(sys.argv[1]) if len(sys.argv) > 1 else Path(__file__).resolve().parent.parent / "results"
DS = ["chaosnli_snli", "chaosnli_mnli", "chaosnli_alphanli", "dices350", "dices990"]
RULES = ["brier", "ce", "nrps"]
J = ["gpt-6-astra", "claude-opus-5-5", "kimi-k3", "glm-5.3", "deepseek-v4.1-flash"]
rd = lambda n: list(csv.DictReader(open(RES / n)))
sk, rk, st, md = rd("skill_all_rules.csv"), rd("rank_agreement.csv"), rd("strata_all_rules.csv"), rd("mdd_all_rules.csv")
summ = json.loads((RES / "summary.json").read_text())
L = ["# Key numbers for Experiment 55 (generated by scripts/summarize.py from results/*.csv; do not edit)", "",
     f"Bootstrap draws {summ['B']} (item resampling), cross-fit folds {summ['folds']}, strata {summ['quintiles']} entropy quintiles, bundle SHA-256 {summ['bundle_sha256'][:16]}.", "",
     "## Skill over the cross-fitted base rate (1 - judge risk / base risk; higher is better; 0 = no better than the base rate)",
     "`-` after a value: Holm-significantly below the base rate (point skill < 0, Holm p < 0.05); `+`: Holm-significantly above; blank: neither.", "",
     "| set | rule (match) | base risk | " + " | ".join(J) + " |", "|---|---|---|" + "---|" * len(J)]
for ds in DS:
    for r in RULES:
        rr = {x["judge"]: x for x in sk if x["dataset"] == ds and x["rule"] == r}
        cells = []
        for j in J:
            x = rr[j]
            mark = "-" if x["significant_below_base"] == "True" else ("+" if x["significant_above_base"] == "True" else "")
            cells.append(f"{float(x['skill']):+.3f}{mark}")
        L.append(f"| {ds} | {r} ({rr[J[0]]['match']}) | {float(rr[J[0]]['base_risk']):.4f} | " + " | ".join(cells) + " |")
L += ["", "## Hypotheses (frozen in PROTOCOL.md)", "",
      f"- H1 (DICES-350, judges Holm-significantly below the base rate, by rule): {summ['h1_dices350_n_significantly_below_base_by_rule']}; holds (at least 3 under each rule): {summ['h1_holds']}.",
      f"- H2 (best judge's skill in the highest-agreement quintile exceeds its skill in the lowest, 15 set-by-rule cells): {summ['h2_cells_holding']} of {summ['h2_cells_total']}; holds: {summ['h2_holds']}.",
      f"- Cells (of 25 per rule) Holm-significantly below the base rate: {summ['n_cells_significantly_below_base_by_rule']}.", "",
      "## Ranking agreement between rules (judges ordered by skill; Kendall tau-b over the five judges; descriptive)", "",
      "| set | rules | tau-b | judge pairs whose order flips (of 10) | best judge under first rule | under second rule |", "|---|---|---|---|---|---|"]
for x in rk:
    L.append(f"| {x['dataset']} | {x['rule_a']} vs {x['rule_b']} | {float(x['kendall_tau_b']):+.2f} | {x['pairs_flipped_of_10']} | {x['best_a']} | {x['best_b']} |")
L += ["", "## Skill by human-agreement quintile (min to max over the five judges; Q1 = most agreement, Q5 = least)", "",
      "| set | rule | Q1 | Q5 |", "|---|---|---|---|"]
for ds in DS:
    for r in RULES:
        cells = []
        for q in ("1", "5"):
            v = [float(x["skill"]) for x in st if x["dataset"] == ds and x["rule"] == r and x["quintile"] == q]
            cells.append(f"{min(v):+.2f} to {max(v):+.2f}")
        L.append(f"| {ds} | {r} | {cells[0]} | {cells[1]} |")
L += ["", "## Minimum detectable difference for a paired judge comparison (N = 400 items, one rating per item, 80% power, 5% level; median and range over the 10 judge pairs; units of the rule)", "",
      "| set | rule | median | min | max |", "|---|---|---|---|---|"]
for x in md:
    L.append(f"| {x['dataset']} | {x['rule']} | {float(x['mdd_N400_k1_median']):.4f} | {float(x['mdd_N400_k1_min']):.4f} | {float(x['mdd_N400_k1_max']):.4f} |")
(RES / "key_numbers.md").write_text("\n".join(L) + "\n")
print("wrote", RES / "key_numbers.md")
