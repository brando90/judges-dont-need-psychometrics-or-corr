#!/usr/bin/env python3
"""Tables and figure for Experiment 52. Usage: python summarize.py RESULTS_DIR FIG_DIR"""
import json, sys
from pathlib import Path
import matplotlib; matplotlib.use("Agg"); import matplotlib.pyplot as plt
res, figd = Path(sys.argv[1]), Path(sys.argv[2]); figd.mkdir(parents=True, exist_ok=True)
p = json.loads((res / "skill_estimator_rows.json").read_text())
E = ["E1_one_rating_known_base", "E2_one_rating_insample_base", "E3_one_rating_leave_one_out_base", "E4_five_ratings_same_items", "E5_five_ratings_equal_total"]
with open(res / "skill_estimator_tables.md", "w") as f:
    f.write("# Experiment 52 tables (generated by scripts/summarize.py)\n\nSynthetic law (PROTOCOL.md). Skill score SS = 1 - S(judge)/S(base); bias = mean estimate minus the exact population SS; SD over 5,000 replicates; Monte Carlo SE of the bias = SD/sqrt(5000). Cells: bias / SD.\n\n")
    for s in ("nrps", "brier", "ce"):
        for j in ("J1_noisy_calibrated", "J2_overconfident", "J3_shifted", "J4_oracle"):
            f.write(f"## score {s}, judge {j} (true SS = {p['truth'][j + '|' + s]:.4f})\n\n| estimator | " + " | ".join(f"n={n}" for n in (25, 50, 100, 200, 500, 1000, 5000)) + " |\n|---|" + "---|" * 7 + "\n")
            for e in E:
                rs = sorted([r for r in p["rows"] if r["score"] == s and r["judge"] == j and r["estimator"] == e], key=lambda r: r["n"])
                f.write(f"| {e} | " + " | ".join(f"{r['bias']:+.4f} / {r['sd']:.4f}" for r in rs) + " |\n")
            f.write("\n")
fig, axes = plt.subplots(1, 2, figsize=(12, 4.5))
for e in E:
    rs = sorted([r for r in p["rows"] if r["score"] == "nrps" and r["judge"] == "J1_noisy_calibrated" and r["estimator"] == e], key=lambda r: r["n"])
    axes[0].plot([r["n"] for r in rs], [r["bias"] for r in rs], marker="o", label=e)
    axes[1].plot([r["n"] for r in rs], [r["sd"] for r in rs], marker="o", label=e)
for ax, yl in zip(axes, ("bias of skill-score estimate (nRPS; synthetic J1)", "SD of skill-score estimate (nRPS; synthetic J1)")):
    ax.set_xscale("log"); ax.set_xlabel("items n (E5: n/5 items with 5 ratings)"); ax.set_ylabel(yl); ax.grid(True, which="major"); ax.grid(True, which="minor", alpha=0.25)
axes[1].set_yscale("log"); axes[0].axhline(0, color="k", lw=0.8); axes[0].legend(fontsize=7)
fig.tight_layout(); fig.savefig(figd / "skill_estimator_bias_sd.png", dpi=140)
