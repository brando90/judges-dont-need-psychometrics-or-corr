#!/usr/bin/env python3
"""Prints (and saves to results/key_numbers.md) every number quoted in RESULTS.md, computed from the CSVs. Deterministic."""
from __future__ import annotations

import csv
import io
import json
import statistics
import sys
from collections import defaultdict
from contextlib import redirect_stdout
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import lib44 as L  # noqa: E402

RES = Path(sys.argv[1]) if len(sys.argv) > 1 else L.ROOT / "results"


def rd(n):
    with open(RES / n, newline="") as f:
        return list(csv.DictReader(f))


def f(x, d=4):
    return f"{float(x):.{d}f}"


def main():
    S = json.loads((RES / "summary.json").read_text())
    print("# Key numbers for RESULTS.md (generated by src/summarize.py from results/*.csv; do not edit)\n")
    print(f"bootstrap draws {S['bootstrap_draws']}, permutations {S['permutations']}, drop_invalid {S['drop_invalid']}, items used {S['items_used']}\n")
    T, J, P = rd("arm_p_tvd.csv"), rd("arm_p_judges.csv"), rd("arm_p_pairs.csv")
    print("## Arm P / P1: mean TVD between pools vs rater-level permutation null (500 permutations)")
    for r in T:
        print(f"- {r['dataset']} {r['contrast']} ({r['pool_A']} vs {r['pool_B']}): raters {r['raters_A']}/{r['raters_B']}, eligible items {r['n_eligible_items']}/{r['n_items']}, "
              f"TVD {f(r['tvd_observed'])}, null mean {f(r['tvd_null_mean'])}, null 95th pct {f(r['tvd_null_p95'])}, raw p {f(r['p_raw'])}, Holm p {f(r['p_holm'])}")
    print(f"- smallest raw p {min(float(r['p_raw']) for r in T):.4f}; cells with Holm p < 0.05: {sum(float(r['p_holm']) < 0.05 for r in T)} of {len(T)}")
    print("\n## Arm P / P2: risk against pool A minus risk against pool B per judge (normalized RPS)")
    for ds in L.DICES:
        for c in L.CONTRASTS:
            rows = [r for r in J if r['dataset'] == ds and r['contrast'] == c]
            d = [float(r['delta_pool']) for r in rows]
            print(f"- {ds} {c}: delta range {min(d):+.4f} to {max(d):+.4f}; smallest raw p {min(float(r['p_raw']) for r in rows):.3f}; smallest Holm p {min(float(r['p_holm']) for r in rows):.3f}; "
                  f"same sign for all five judges: {all(x > 0 for x in d) or all(x < 0 for x in d)}")
    print(f"- cells with Holm p < 0.05: {sum(float(r['p_holm']) < 0.05 for r in J)} of {len(J)}; largest |delta| {max(abs(float(r['delta_pool'])) for r in J):.4f}")
    print("\n## Arm P / P3: ranking under pool A vs pool B")
    agg = defaultdict(lambda: dict(rev=0, n=0, tau=None, minholm=1.0, maxD=0.0))
    for r in P:
        a = agg[(r['dataset'], r['contrast'])]
        a['n'] += 1; a['rev'] += r['point_reversal'] == 'True'; a['tau'] = float(r['tau_b_AB'])
        a['minholm'] = min(a['minholm'], float(r['p_holm'])); a['maxD'] = max(a['maxD'], abs(float(r['interaction_D'])))
    for k, a in agg.items():
        print(f"- {k[0]} {k[1]}: Kendall tau-b {a['tau']:.1f}, point-estimate reversals {a['rev']} of {a['n']}, smallest Holm p {a['minholm']:.3f}, largest |D| {a['maxD']:.4f}")
    print(f"- Holm-significant interaction cells {S['P3_holm_significant_interactions']} of {len(P)}; point reversals {S['P3_point_reversals']}; pool-dependent orderings {S['P3_pool_dependent_orderings']}")
    for r in P:
        if r['point_reversal'] == 'True':
            print(f"  - reversed: {r['dataset']} {r['contrast']} {r['judge_a']} vs {r['judge_b']}: difference under pool A {float(r['diff_pool_A']):+.4f}, under pool B {float(r['diff_pool_B']):+.4f}, raw p {f(r['p_raw'], 3)}")
    print("\n## Arm S")
    G, C = rd("arm_s_gain.csv"), rd("arm_s_curves.csv")
    print(f"- delta_G > 0 in {S['H_S1']['delta_G_positive']} of {S['H_S1']['cells']} cells; interval excludes 0 (above) in {S['H_S1']['ci_excludes_0_above']}; argmax unchanged in all cells: {S['H_S1']['argmax_unchanged_all']}")
    print(f"- delta_G range {min(float(r['delta_G']) for r in G):+.4f} to {max(float(r['delta_G']) for r in G):+.4f}")
    print(f"- sharpening to tau 0.5 improves the consensus-stratum risk in {sum(float(r['gain_consensus']) > 0 for r in G)} of {len(G)} cells and the contested-stratum risk in {sum(float(r['gain_contested']) > 0 for r in G)}")
    for t in (0.5, 0.75, 1.0, 1.5, 2.0):
        print(f"- best tau = {t}: consensus {sum(float(r['best_tau_consensus']) == t for r in G)} cells, contested {sum(float(r['best_tau_contested']) == t for r in G)} cells")
    print(f"- best tau sharper on consensus than on contested in {sum(float(r['best_tau_consensus']) < float(r['best_tau_contested']) for r in G)} cells, equal in {sum(float(r['best_tau_consensus']) == float(r['best_tau_contested']) for r in G)}")
    print("- judge-mean risk by stratum and tau (primary score):")
    agg2 = defaultdict(lambda: defaultdict(list))
    for r in C:
        agg2[(r['dataset'], r['stratum'])][float(r['tau'])].append(float(r['risk_primary']))
    seen = {}
    for r in C:
        seen[(r['dataset'], r['stratum'])] = float(r['median_agreement'])
    for k, d in agg2.items():
        print(f"  - {k[0]} {k[1]} (median half-A agreement {seen[k]:.2f}): " + ", ".join(f"tau {t}: {sum(v) / len(v):.4f}" for t, v in sorted(d.items())))
    print("\n## Arm J")
    JS, PM = rd("arm_j_jsb.csv"), rd("arm_j_permutation.csv")
    for ds in L.DATASETS:
        rows = [r for r in JS if r['dataset'] == ds]
        print(f"- {ds}: bins {rows[0]['n_bins']}, Kendall tau-b (JSb ranking vs primary-score ranking) {float(rows[0]['tau_b_jsb_vs_primary_risk']):+.1f}; "
              f"JSb order {[r['judge'] for r in sorted(rows, key=lambda r: float(r['jsb']))]}; risk order {[r['judge'] for r in sorted(rows, key=lambda r: float(r['primary_risk']))]}")
    print(f"- max |change in JSb| over 200 within-bin shuffles x 25 cells: {S['H_J1']['max_abs_jsb_change']:.2e}")
    ws = [float(r['risk_permuted_minus_original_mean']) for r in PM]
    print(f"- risk worsens after the shuffle in {S['H_J2']['permuted_worse']} of {S['H_J2']['cells']} cells; smallest increase {min(ws):+.4f}, largest {max(ws):+.4f}; largest standard error {max(float(r['risk_permuted_minus_original_se']) for r in PM):.4f}")
    for ds in L.DATASETS:
        v = [float(r['risk_permuted_minus_original_mean']) for r in PM if r['dataset'] == ds]
        print(f"  - {ds}: increase range {min(v):+.4f} to {max(v):+.4f}")
    print("\n## Arm M")
    M, CK = rd("arm_m_pairs.csv"), rd("arm_m_check.csv")
    for ds in L.DATASETS:
        rows = [r for r in M if r['dataset'] == ds]
        obs = [abs(float(r['observed_diff'])) for r in rows]; n80 = sorted(float(r['n80_k1']) for r in rows)
        print(f"- {ds}: observed |difference| {min(obs):.4f} to {max(obs):.4f}; sigma_b^2 {min(float(r['sigma_b2']) for r in rows):.4f} to {max(float(r['sigma_b2']) for r in rows):.4f}; "
              f"sigma_w^2 {min(float(r['sigma_w2']) for r in rows):.4f} to {max(float(r['sigma_w2']) for r in rows):.4f}; MDD(400,1) {min(float(r['mdd_N400_k1']) for r in rows):.4f} to {max(float(r['mdd_N400_k1']) for r in rows):.4f}; "
              f"MDD(400,10) {min(float(r['mdd_N400_k10']) for r in rows):.4f} to {max(float(r['mdd_N400_k10']) for r in rows):.4f}; pairs with N_80 <= 400 at k = 1: {S['M_resolvable_N400_k1_by_set'][ds]}; N_80 median {statistics.median(n80):.0f}, smallest {n80[0]:.0f}, largest {n80[-1]:.0f}")
    print(f"- H-M1: {S['H_M1']['within_0p9_1p1']} of {S['H_M1']['cells']} cells within 0.9 to 1.1 of V_sub; ratio to V_sub {min(float(r['ratio_to_v_sub']) for r in CK):.3f} to {max(float(r['ratio_to_v_sub']) for r in CK):.3f}; "
          f"ratio to V(N,k) {min(float(r['ratio_to_v_planning']) for r in CK):.3f} to {max(float(r['ratio_to_v_planning']) for r in CK):.3f}; frozen (pre-amendment) criterion 0.6 to 1.1 x V(N,k) met in {sum(0.6 <= float(r['ratio_to_v_planning']) <= 1.1 for r in CK)} of {len(CK)}")
    print(f"- H-M2 identity: {S['H_M2']}")
    # MDD ratio k=1 to k=10 at N=400
    rat = [float(r['mdd_N400_k1']) / float(r['mdd_N400_k10']) for r in M]
    print(f"- MDD(400,1) / MDD(400,10): median {statistics.median(rat):.2f}, range {min(rat):.2f} to {max(rat):.2f}")


if __name__ == "__main__":
    buf = io.StringIO()
    with redirect_stdout(buf):
        main()
    text = buf.getvalue()
    (RES / "key_numbers.md").write_text(text)
    print(text)
